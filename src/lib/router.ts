import type { LogEntry, ModelInfo, RoutingResult, Tier } from './types';
import { BASELINE_MODEL, MODELS } from './constants';

const COMPLEXITY_KEYWORDS = [
  'derive', 'analyze', 'architect', 'refactor', 'proof', 'debug',
  'optimize', 'implement', 'design', 'evaluate', 'synthesize',
  'compare', 'contrast', 'reasoning', 'theorem', 'algorithm',
  'complex', 'advanced', 'detailed', 'comprehensive',
  'step-by-step', 'trade-off', 'tradeoffs', 'consensus',
  'distributed', 'concurrency', 'parallel', 'asynchronous',
  'refactor', 'migration', 'scalability', 'performance',
];

const MULTI_STEP_INDICATORS = [
  'first', 'then', 'after that', 'finally', 'step',
  'next', 'subsequently', 'lastly', 'begin by',
];

export function calculateDifficulty(prompt: string): number {
  const lower = prompt.toLowerCase();
  const words = prompt.trim().split(/\s+/).filter(Boolean);
  const wordCount = words.length;
  const charCount = prompt.length;

  let score = 0;

  // Length factor: longer prompts tend to be more complex
  if (wordCount > 0) {
    const lengthScore = Math.min(wordCount / 120, 1) * 0.35;
    score += lengthScore;
  }

  // Keyword density
  let keywordHits = 0;
  for (const kw of COMPLEXITY_KEYWORDS) {
    if (lower.includes(kw)) keywordHits++;
  }
  const keywordScore = Math.min(keywordHits / 5, 1) * 0.35;
  score += keywordScore;

  // Multi-step instruction patterns
  let multiStepHits = 0;
  for (const indicator of MULTI_STEP_INDICATORS) {
    if (lower.includes(indicator)) multiStepHits++;
  }
  const multiStepScore = Math.min(multiStepHits / 3, 1) * 0.15;
  score += multiStepScore;

  // Character density (code-heavy prompts tend to be longer per word)
  if (wordCount > 0) {
    const avgWordLen = charCount / wordCount;
    if (avgWordLen > 7) score += 0.075;
  }

  // Punctuation / structure complexity
  const newlines = (prompt.match(/\n/g) || []).length;
  if (newlines > 2) score += 0.05;

  // Question depth — multiple sentences suggest multi-part queries
  const sentences = prompt.split(/[.!?]+/).filter((s) => s.trim().length > 0).length;
  if (sentences >= 3) score += 0.05;

  // Code indicators
  if (/[{};()=]/.test(prompt) && /function|class|def |const |let |var /i.test(prompt)) {
    score += 0.05;
  }

  return Math.min(Math.round(score * 100) / 100, 1);
}

export function getTier(difficulty: number): Tier {
  if (difficulty < 0.35) return 'cheap';
  if (difficulty <= 0.7) return 'mid';
  return 'hard';
}

function estimateTokens(text: string): number {
  return Math.ceil(text.length / 4);
}

function generateSimulatedOutput(prompt: string, model: ModelInfo): string {
  const tier = model.tier;
  if (tier === 'cheap') {
    return `Here's a concise answer:\n\nBased on the query "${prompt.slice(0, 60)}${prompt.length > 60 ? '...' : ''}", the response is straightforward. The key point is addressed directly without extensive elaboration.\n\n— Generated by ${model.name} (optimized for speed and cost efficiency).`;
  }
  if (tier === 'mid') {
    return `Here's a structured response:\n\n**Analysis:**\nThe prompt requires moderate reasoning. I'll break this down systematically.\n\n**Approach:**\n1. Identify the core requirements\n2. Apply relevant patterns and best practices\n3. Provide a working solution with explanation\n\n**Solution:**\n\`\`\`\n// Implementation tailored to your request\n// Handles edge cases and follows conventions\n\`\`\`\n\n**Notes:** Consider error handling and input validation for production use.\n\n— Generated by ${model.name} (balanced quality and cost).`;
  }
  return `Here's a comprehensive, deeply reasoned response:\n\n**Deep Analysis:**\nThis query involves significant architectural and theoretical considerations. Let me derive the solution rigorously.\n\n**Theoretical Foundation:**\n- We begin by establishing the formal properties and invariants\n- Multiple competing approaches must be evaluated against constraints\n- Trade-offs between consistency, availability, and partition tolerance apply\n\n**Step-by-Step Derivation:**\n1. **Formal Model:** Define the system in terms of actors, state, and transitions\n2. **Correctness Proof:** Show that safety and liveness properties hold\n3. **Complexity Analysis:** Time and space complexity under adversarial conditions\n4. **Practical Implications:** Map theory to engineering decisions\n\n**Conclusion:**\nThe solution balances theoretical guarantees with practical performance. Each design choice has documented trade-offs.\n\n— Generated by ${model.name} (maximum reasoning depth).`;
}

export function routePrompt(prompt: string): RoutingResult {
  const difficulty = calculateDifficulty(prompt);
  const tier = getTier(difficulty);
  const model = MODELS[tier];

  const promptTokens = estimateTokens(prompt);

  // Completion length scales with tier
  const baseCompletion = 50 + difficulty * 350;
  const completionTokens = Math.round(baseCompletion + (Math.random() - 0.5) * 40);

  const actualCost =
    (promptTokens / 1000) * model.costPer1kPrompt +
    (completionTokens / 1000) * model.costPer1kCompletion;

  const baselineCost =
    (promptTokens / 1000) * BASELINE_MODEL.costPer1kPrompt +
    (completionTokens / 1000) * BASELINE_MODEL.costPer1kCompletion;

  const savings = baselineCost - actualCost;
  const savingsPct = baselineCost > 0 ? (savings / baselineCost) * 100 : 0;

  const latencyMs = Math.round(
    (completionTokens / 1000) * model.latencyPer1k * 1000 +
      (Math.random() - 0.5) * 200 +
      300
  );

  const simulatedOutput = generateSimulatedOutput(prompt, model);

  return {
    difficulty,
    tier,
    model,
    promptTokens,
    completionTokens,
    actualCost,
    baselineCost,
    savings,
    savingsPct,
    latencyMs,
    simulatedOutput,
  };
}

export function resultToLog(result: RoutingResult, prompt: string): LogEntry {
  return {
    id: `${Date.now()}-${Math.random().toString(36).slice(2, 8)}`,
    timestamp: Date.now(),
    prompt,
    difficulty: result.difficulty,
    tier: result.tier,
    modelName: result.model.name,
    actualCost: result.actualCost,
    baselineCost: result.baselineCost,
    savings: result.savings,
    latencyMs: result.latencyMs,
    promptTokens: result.promptTokens,
    completionTokens: result.completionTokens,
  };
}
